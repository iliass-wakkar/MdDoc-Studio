"""
Typst Compiler for MdDoc Studio.
Translates the MdDoc DocumentModel (IR) into high-fidelity Typst typesetting code.
Enables publication-grade vector PDF generation with exact theme colors, booktabs tables,
executive cover pages, and GFM admonition callouts.
"""

import os
import shutil
import subprocess
from typing import Optional, Dict, Any, List

from .ir import (
    DocumentModel,
    DocumentMetadata,
    ThemePalette,
    HeadingBlock,
    ParagraphBlock,
    CodeBlock,
    BlockquoteBlock,
    AdmonitionBlock,
    TableBlock,
    ListBlock,
    HorizontalRuleBlock,
    InlineRun,
    markdown_to_ir,
)


def _escape_typst_text(text: str) -> str:
    """Escape special Typst syntax characters in plain text runs."""
    # Typst specials: [ ] $ # _ * @ ` \ < >
    # For content mode, backslash, hash, brackets, asterisks need escaping
    text = text.replace("\\", "\\\\")
    text = text.replace("#", "\\#")
    text = text.replace("[", "\\[").replace("]", "\\]")
    text = text.replace("$", "\\$")
    text = text.replace("@", "\\@")
    text = text.replace("<", "\\<").replace(">", "\\>")
    return text


def _render_runs_to_typst(runs: List[InlineRun]) -> str:
    """Convert a list of InlineRun objects into Typst inline markup."""
    parts = []
    for r in runs:
        if r.code:
            parts.append(f"`{r.text}`")
            continue

        raw = _escape_typst_text(r.text)
        formatted = raw
        if r.bold and r.italic:
            formatted = f"*_{formatted}_*"
        elif r.bold:
            formatted = f"*{formatted}*"
        elif r.italic:
            formatted = f"_{formatted}_"

        if r.link:
            formatted = f'#link("{r.link}")[{formatted}]'

        parts.append(formatted)

    return "".join(parts)


def compile_ir_to_typst(doc: DocumentModel) -> str:
    """
    Compile a DocumentModel IR into complete, standalone Typst (.typ) source code.
    """
    m: DocumentMetadata = doc.metadata
    t: ThemePalette = doc.theme

    typ = []

    # 1. Page Configuration & Fonts
    page_size = "us-letter" if m.page_size.upper() == "LETTER" else "a4"

    typ.append(f"""// Generated by MdDoc Studio — Publication-Quality Typesetting
#set page(
  paper: "{page_size}",
  margin: (top: 2.5cm, bottom: 2.5cm, left: 2.5cm, right: 2.5cm),
  header: context {{
    let page_num = counter(page).get().first()
    let has_cover = {str(m.show_cover).lower()}
    let show_header = {str(m.show_header).lower()}
    if show_header and (not has_cover or page_num > 1) {{
      align(right)[
        #text(size: 8.5pt, fill: rgb("{t.light_text}"), font: "{t.font_body}")[{_escape_typst_text(m.title or "")}]
        #v(2pt)
        #line(length: 100%, stroke: 0.5pt + rgb("{t.table_border}"))
      ]
    }}
  }},
  footer: context {{
    let page_num = counter(page).get().first()
    let has_cover = {str(m.show_cover).lower()}
    if not has_cover or page_num > 1 {{
      align(center)[
        #text(size: 9pt, fill: rgb("{t.light_text}"), font: "{t.font_body}")[Page #page_num of #counter(page).final().first()]
      ]
    }}
  }}
)

#set text(
  font: ("{t.font_body}", "Segoe UI", "Calibri", "Arial"),
  size: 10.5pt,
  fill: rgb("{t.text}")
)

#set par(
  leading: 0.7em,
  justify: false
)

// Heading Styles
#show heading.where(level: 1): it => block(
  above: 1.8em,
  below: 1.2em,
  breakable: false,
  [
    #text(size: 20pt, weight: "bold", fill: rgb("{t.primary}"), font: ("{t.font_heading}", "Georgia", "Cambria"))[#it.body]
    #v(4pt)
    #line(length: 100%, stroke: 2pt + rgb("{t.secondary}"))
  ]
)

#show heading.where(level: 2): it => block(
  above: 1.4em,
  below: 0.8em,
  breakable: false,
  [
    #text(size: 15pt, weight: "bold", fill: rgb("{t.secondary}"), font: ("{t.font_heading}", "Georgia", "Cambria"))[#it.body]
  ]
)

#show heading.where(level: 3): it => block(
  above: 1.2em,
  below: 0.6em,
  breakable: false,
  [
    #text(size: 12.5pt, weight: "bold", fill: rgb("{t.primary}"), font: ("{t.font_heading}", "Georgia", "Cambria"))[#it.body]
  ]
)

// Admonition Function Definition
#let admonition(variant: "NOTE", title: "Note", body) = {{
  let border-col = rgb("{t.primary}")
  let bg-col = rgb("F0F4F8")
  let icon = "ℹ"

  if variant == "TIP" {{
    border-col = rgb("10B981")
    bg-col = rgb("F0FDF4")
    icon = "💡"
  }} else if variant == "IMPORTANT" {{
    border-col = rgb("7C3AED")
    bg-col = rgb("FAF5FF")
    icon = "★"
  }} else if variant == "WARNING" {{
    border-col = rgb("D97706")
    bg-col = rgb("FFFBEB")
    icon = "⚠"
  }} else if variant == "CAUTION" {{
    border-col = rgb("EF4444")
    bg-col = rgb("FEF2F2")
    icon = "🛑"
  }}

  rect(
    width: 100%,
    radius: 4pt,
    stroke: (left: 3.5pt + border-col, rest: 0.5pt + rgb("{t.table_border}")),
    fill: bg-col,
    inset: (x: 12pt, y: 10pt)
  )[
    #text(weight: "bold", fill: border-col)[#icon #h(4pt) #title]
    #v(4pt)
    #text(fill: rgb("{t.text}"))[#body]
  ]
}}
""")

    # 2. Cover Page
    if m.show_cover and m.title:
        typ.append(f"""
// Cover Page
#align(center + horizon)[
  #text(fill: rgb("{t.secondary}"), size: 14pt)[━━━━━━━━━━━━━━━]
  #v(20pt)
  #text(fill: rgb("{t.primary}"), font: ("{t.font_heading}", "Cambria", "Georgia"), size: 28pt, weight: "bold")[{_escape_typst_text(m.title)}]
""")
        if m.subtitle:
            typ.append(f"""  #v(8pt)
  #text(fill: rgb("{t.light_text}"), font: "{t.font_body}", size: 14pt, style: "italic")[{_escape_typst_text(m.subtitle)}]
""")
        typ.append(f"""  #v(24pt)
  #text(fill: rgb("{t.secondary}"), size: 12pt)[─────────────────────]
""")
        if m.author:
            typ.append(f"""  #v(14pt)
  #text(fill: rgb("{t.text}"), font: "{t.font_body}", size: 12pt, weight: "bold")[By {_escape_typst_text(m.author)}]
""")
        if m.date:
            typ.append(f"""  #v(6pt)
  #text(fill: rgb("{t.light_text}"), font: "{t.font_body}", size: 10.5pt)[{_escape_typst_text(m.date)}]
""")
        typ.append(f"""  #v(20pt)
  #text(fill: rgb("{t.secondary}"), size: 14pt)[━━━━━━━━━━━━━━━]
]
#pagebreak()
""")

    # 3. Table of Contents
    if m.show_toc:
        typ.append("""
// Table of Contents
#outline(title: "Table of Contents", indent: auto)
#pagebreak()
""")

    # 4. Body Content Blocks
    for b in doc.blocks:
        if isinstance(b, HeadingBlock):
            h_runs = _render_runs_to_typst(b.runs)
            eqs = "=" * b.level
            typ.append(f"\n{eqs} {h_runs}\n")

        elif isinstance(b, ParagraphBlock):
            p_text = _render_runs_to_typst(b.runs)
            if p_text.strip():
                typ.append(f"\n{p_text}\n")

        elif isinstance(b, CodeBlock):
            lang_str = b.language or ""
            typ.append(f"\n```{lang_str}\n{b.code}\n```\n")

        elif isinstance(b, BlockquoteBlock):
            quote_runs = []
            for p in b.paragraphs:
                quote_runs.append(_render_runs_to_typst(p.runs))
            q_content = " ".join(quote_runs)
            typ.append(f"""
#rect(width: 100%, fill: rgb("{t.table_row_alt}"), stroke: (left: 3pt + rgb("{t.secondary}"), rest: none), inset: (x: 10pt, y: 8pt))[
  #text(fill: rgb("{t.text}"), style: "italic")[{q_content}]
]
""")

        elif isinstance(b, AdmonitionBlock):
            ad_body_parts = []
            for p in b.content:
                ad_body_parts.append(_render_runs_to_typst(p.runs))
            ad_text = "\n\n".join(ad_body_parts)
            typ.append(f"""
#admonition(variant: "{b.variant}", title: "{_escape_typst_text(b.title)}")[
  {ad_text}
]
""")

        elif isinstance(b, TableBlock):
            if not b.rows:
                continue
            cols = len(b.rows[0].cells)
            col_widths = ", ".join(["1fr"] * cols)

            table_cells_typ = []
            for row in b.rows:
                for c in row.cells:
                    cell_text = _render_runs_to_typst(c.runs)
                    if c.is_header:
                        table_cells_typ.append(f'[#text(weight: "bold", fill: rgb("{t.table_header_text}"))[{cell_text}]]')
                    else:
                        table_cells_typ.append(f'[{cell_text}]')

            cells_joined = ",\n  ".join(table_cells_typ)
            typ.append(f"""
#align(center)[
  #table(
    columns: ({col_widths}),
    stroke: (x, y) => if y == 0 {{ (bottom: 1.5pt + rgb("{t.primary}")) }} else if y == 1 {{ (bottom: 1pt + rgb("{t.table_border}")) }} else {{ (bottom: 0.5pt + rgb("{t.table_border}")) }},
    fill: (x, y) => if y == 0 {{ rgb("{t.table_header_bg}") }} else if calc.even(y) {{ rgb("{t.table_row_alt}") }} else {{ none }},
    inset: 7pt,
    {cells_joined}
  )
]
""")

        elif isinstance(b, ListBlock):
            typ.append("")
            for item in b.items:
                prefix = "+ " if item.is_ordered else "- "
                indent = "  " * item.level
                item_runs = _render_runs_to_typst(item.runs)
                typ.append(f"{indent}{prefix}{item_runs}")
            typ.append("")

        elif isinstance(b, HorizontalRuleBlock):
            typ.append(f'\n#v(10pt)\n#line(length: 100%, stroke: 0.5pt + rgb("{t.table_border}"))\n#v(10pt)\n')

    return "\n".join(typ)


def compile_markdown_to_typst(
    md_text: str,
    theme_name: str = "modern",
    custom_theme: Optional[Dict[str, Any]] = None,
    override_metadata: Optional[Dict[str, Any]] = None
) -> str:
    """Convenience function: parses markdown to IR and renders Typst markup."""
    doc = markdown_to_ir(
        md_text=md_text,
        theme_name=theme_name,
        custom_theme=custom_theme,
        override_metadata=override_metadata
    )
    return compile_ir_to_typst(doc)


def compile_typst_to_pdf(typst_source: str, output_pdf_path: str) -> bool:
    """
    Compile Typst code into PDF using the Typst CLI if available on the system.
    Returns True if compilation succeeded, False otherwise.
    """
    typst_bin = shutil.which("typst")
    if not typst_bin:
        return False

    os.makedirs(os.path.dirname(os.path.abspath(output_pdf_path)), exist_ok=True)
    tmp_typ_path = output_pdf_path + ".tmp.typ"

    try:
        with open(tmp_typ_path, "w", encoding="utf-8") as f:
            f.write(typst_source)

        proc = subprocess.run(
            [typst_bin, "compile", tmp_typ_path, output_pdf_path],
            capture_output=True,
            text=True
        )
        return proc.returncode == 0
    finally:
        if os.path.exists(tmp_typ_path):
            try:
                os.remove(tmp_typ_path)
            except Exception:
                pass
